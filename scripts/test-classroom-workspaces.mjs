import './test-browser-origin.mjs';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { withClassroomTestApp } from './classroom-test-app.mjs';
await withClassroomTestApp(async ({ db, base, request }) => {
  const password = 'workspace-test-password';
  const teacher = await db.user.create({ data: { name: 'Teacher', email: 'workspace-teacher@example.test', password, role: 'MEMBER', status: 'ACTIVE' } });
  await db.classroomMembership.create({ data: { userId: teacher.id, departmentOrDesignation: 'Faculty', status: 'APPROVED' } });
  const login = await request('/api/auth/login', { method: 'POST', body: { email: teacher.email, password, workspace: 'CLASS' } });
  assert.equal(login.response.status, 200);
  const forbiddenShell = await request('/dashboard', { cookie: login.cookie });
  assert.ok([307, 308].includes(forbiddenShell.response.status), 'teacher-only identity must not render the Events layout');
  assert.match(forbiddenShell.response.headers.get('location'), /^\/class/);
  const classShell = await request('/class', { cookie: login.cookie });
  assert.equal(classShell.response.status, 200);
  const eventsRequest = await request('/api/auth/events-application', { method: 'POST', cookie: login.cookie, body: { commandId: crypto.randomUUID() } });
  assert.equal(eventsRequest.response.status, 200, eventsRequest.text);
  assert.equal((await db.classroomMembership.findUniqueOrThrow({ where: { userId: teacher.id } })).status, 'APPROVED');
  const applicant = await db.user.create({ data: { name: 'Pending Teacher', email: 'workspace-pending@example.test', password, role: 'MEMBER' } });
  await db.classroomMembership.create({ data: { userId: applicant.id, departmentOrDesignation: 'Faculty' } });
  const pendingLogin = await request('/api/auth/login', { method: 'POST', body: { email: applicant.email, password, workspace: 'CLASS' } });
  assert.equal((await request('/class', { cookie: pendingLogin.cookie })).response.status, 307);
  assert.equal((await request('/class/access', { cookie: pendingLogin.cookie })).response.status, 200);
  const admin = await db.user.create({ data: { name: 'Administrator', email: 'workspace-admin@example.test', password, role: 'ADMIN', status: 'ACTIVE' } });
  const adminLogin = await request('/api/auth/login', { method: 'POST', body: { email: admin.email, password, workspace: 'CLASS' } });
  assert.equal(adminLogin.response.status, 200);
  const run = spawnSync('python3', ['scripts/test-classroom-workspaces.py'], { env: { ...process.env, CLASSROOM_TEST_BASE: base, CLASSROOM_TEACHER_COOKIE: login.cookie, CLASSROOM_PENDING_COOKIE: pendingLogin.cookie, CLASSROOM_ADMIN_COOKIE: adminLogin.cookie, CLASSROOM_TEACHER_ID: teacher.id }, encoding: 'utf8' });
  assert.equal(run.status, 0, `${run.stdout}\n${run.stderr}`);
  console.log(run.stdout);
});
