import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { withClassroomTestApp } from './classroom-test-app.mjs';
await withClassroomTestApp(async ({ db, request }) => {
  const pending = await db.user.create({ data: { name: 'Applicant', email: 'applicant@example.test', password: 'test-password', role: 'MEMBER', status: 'PENDING' } });
  await db.classroomMembership.create({ data: { userId: pending.id, departmentOrDesignation: 'Faculty' } });
  const teacherLogin = await request('/api/auth/login', { method: 'POST', body: { email: pending.email, password: 'test-password', workspace: 'CLASS' } });
  assert.equal(teacherLogin.response.status, 200, `pending Class login: ${teacherLogin.text}`);
  assert.ok(teacherLogin.cookie);
  assert.equal(teacherLogin.json.data.capabilities.events, false);
  assert.equal(teacherLogin.json.data.capabilities.classroom, false);
  const denied = await request('/api/students', { cookie: teacherLogin.cookie });
  assert.equal(denied.response.status, 403);
  const own = await request('/api/classroom/application', { cookie: teacherLogin.cookie });
  assert.equal(own.response.status, 200);
  assert.equal(own.json.data.userId, pending.id);
  const admin = await db.user.create({ data: { name: 'Admin', email: 'admin@example.test', password: 'test-password', role: 'ADMIN', status: 'ACTIVE' } });
  const adminLogin = await request('/api/auth/login', { method: 'POST', body: { email: admin.email, password: 'test-password' } });
  assert.equal(adminLogin.response.status, 200, adminLogin.text);
  const decision = await request(`/api/admin/classroom/teachers/${pending.id}`, { method: 'PATCH', cookie: adminLogin.cookie, body: { commandId: randomUUID(), expectedRevision: 0, action: 'APPROVE' } });
  assert.equal(decision.response.status, 200, decision.text);
  const refresh = await request('/api/auth/session', { cookie: teacherLogin.cookie });
  assert.equal(refresh.json.data.capabilities.classroom, true);
  assert.equal(refresh.json.data.capabilities.events, false);
  const forged = await request(`/api/admin/classroom/teachers/${pending.id}`, { method: 'PATCH', cookie: teacherLogin.cookie, body: { commandId: randomUUID(), expectedRevision: 1, action: 'APPROVE' } });
  assert.equal(forged.response.status, 403);
  const user = await db.user.findUniqueOrThrow({ where: { id: pending.id } });
  assert.equal(user.role, 'MEMBER'); assert.equal(user.status, 'PENDING');
  const signup = await request('/api/auth/signup', { method: 'POST', body: { name: 'New Teacher', email: 'new@example.test', password: 'new-password', workspace: 'CLASS', departmentOrDesignation: 'Science' } });
  assert.equal(signup.response.status, 201, signup.text);
  assert.equal((await db.user.findUniqueOrThrow({ where: { email: 'new@example.test' } })).role, 'MEMBER');
  const disabled = await db.user.update({ where: { id: pending.id }, data: { accountState: 'DISABLED' } });
  const stale = await request('/api/classroom/application', { cookie: teacherLogin.cookie });
  assert.equal(stale.response.status, 403);
  assert.equal(stale.json.code, 'ACCOUNT_DISABLED');
  assert.equal(disabled.status, 'PENDING');
  console.log('PASS Classroom identity login, approval, workspace isolation, application ownership, signup and global disable.');
});
